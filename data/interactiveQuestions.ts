const generatedInteractiveQuestions: string[] = [];
let counter = 1;

for (const intro of introVariants) {
    for (const action of actionVariants) {
        for (const closing of closingVariants) {
            generatedInteractiveQuestions.push(
                `سؤال تفاعلي رقم ${counter}: ${intro}. ${action} ${closing}`
            );
            counter += 1;
        }
    }
}

export const INTERACTIVE_QUESTIONS = generatedInteractiveQuestions.slice(0, 1500);

export const getRandomInteractiveQuestion = () => {
    if (INTERACTIVE_QUESTIONS.length === 0) {
        return 'جاهز للعب؟ احكي لي لغز أو لعبة تحب نبدأ فيها!';
    }
    const randomIndex = Math.floor(Math.random() * INTERACTIVE_QUESTIONS.length);
    return INTERACTIVE_QUESTIONS[randomIndex];
};
